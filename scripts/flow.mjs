// The booking path, end to end: 30 nights for two in the Mini Suite VT, through the checkout to the WhatsApp link.
import { chromium, webkit } from 'playwright';
const BASE = process.env.BASE || 'http://127.0.0.1:4329/tu-parada-cuenca/';
const lang = process.argv[2] || '';
const b = await (process.env.ENGINE === 'webkit' ? webkit : chromium).launch();
const page = await (await b.newContext({ viewport: { width: Number(process.env.W || 1280), height: 900 } })).newPage();
const errs = []; page.on('pageerror', (e) => errs.push(String(e)));
const rooms = lang ? 'en/rooms/' : 'habitaciones/';
await page.goto(`${BASE}${rooms}?in=2026-12-01&out=2026-12-31&adults=2&children=0`, { waitUntil: 'networkidle' });
console.log('summary:', await page.locator('[data-sum]').innerText());
await page.selectOption('[data-room="mini-suite-vt"]', '1');
console.log('quote:', (await page.locator('[data-quote]').innerText()).replace(/\n/g, ' | '));
await page.selectOption('[data-room="mini-suite-ab"]', '1');
console.log('with AB (no rate):', (await page.locator('[data-quote]').innerText()).replace(/\n/g, ' | '));
await page.selectOption('[data-room="mini-suite-ab"]', '0');
await page.selectOption('[data-room="mini-suite-vt"]', '0');
await page.selectOption('[data-room="eco"]', '1');
console.log('eco for 2 warn:', await page.locator('[data-warn]').innerText());
await page.selectOption('[data-room="eco"]', '0');
await page.selectOption('[data-room="mini-suite-vt"]', '1');
await Promise.all([page.waitForURL(/reservar|book/), page.locator('[data-reserve]').click()]);
console.log('checkout url:', page.url().replace(BASE, ''));
console.log('side quote:', (await page.locator('.co-quote').innerText()).replace(/\n/g, ' | '));
await page.fill('[name=first]', 'John'); await page.fill('[name=last]', 'Larson'); await page.fill('[name=phone]', '+1 956 555 0123');
await page.selectOption('[name=arrival]', { index: 3 }); await page.check('[name=luggage]');
await page.locator('.co-next').click();
await page.waitForSelector('[data-step="3"]:not([hidden])');
console.log('--- message ---\n' + (await page.locator('[data-msg]').innerText()));
console.log('send href:', (await page.locator('[data-send]').getAttribute('href')).slice(0, 60));
console.log('errors:', errs);
await b.close();
